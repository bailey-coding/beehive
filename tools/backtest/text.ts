// Pure text helpers: issue-source extraction, identifier overlap, token edit distance.

const TRAILER = /^(co-authored-by|signed-off-by|generated by|generated with|claude-session)\b/i;

/** Issue source per plan filter 5: subject + body paragraphs, minus trailers and the solution bullet list. */
export function extractIssueSource(subject: string, body: string): { subject: string; body: string } {
  const desc = subject.replace(/^step:\s*/i, '').split(/\s*\|\s*(task|spec|confidence):/i)[0].trim();
  const lines = body.split('\n').filter((l) => !TRAILER.test(l.trim()));
  const cut = lines.findIndex((l) => /^\s*[-*]\s+/.test(l));
  const kept = (cut >= 0 ? lines.slice(0, cut) : lines).join('\n').trim();
  return { subject: desc, body: kept };
}

const IDENT = /[A-Za-z_$][A-Za-z0-9_$]{5,}/g;

export function identifiersOf(text: string): Set<string> {
  return new Set(text.match(IDENT) ?? []);
}

/**
 * Leakage test 2: identifiers that appear in the spec (or issue text) AND in the held-out diff's added lines,
 * but in neither the issue text nor the base tree. Such a word can only have come from the future change.
 */
export function overlapFlags(opts: { text: string; issueText: string; diffAdded: string; baseTokens: Set<string> }): string[] {
  const inDiff = identifiersOf(opts.diffAdded);
  const inIssue = identifiersOf(opts.issueText);
  const out: string[] = [];
  for (const id of identifiersOf(opts.text)) {
    if (inDiff.has(id) && !inIssue.has(id) && !opts.baseTokens.has(id)) out.push(id);
  }
  return out.sort();
}

export function tokens(s: string): string[] {
  return s.split(/[^A-Za-z0-9_$./{}:-]+/).filter(Boolean);
}

/** Token-level Levenshtein distance divided by the longer token count. 0 = identical, 1 = disjoint. */
export function normalizedTokenLevenshtein(a: string, b: string): number {
  const x = tokens(a);
  const y = tokens(b);
  if (x.length === 0 && y.length === 0) return 0;
  let prev = Array.from({ length: y.length + 1 }, (_, i) => i);
  for (let i = 1; i <= x.length; i++) {
    const cur = [i];
    for (let j = 1; j <= y.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (x[i - 1] === y[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[y.length] / Math.max(x.length, y.length);
}

export function jaccard(a: string, b: string): number {
  const x = new Set(tokens(a));
  const y = new Set(tokens(b));
  if (x.size === 0 && y.size === 0) return 1;
  let inter = 0;
  for (const t of x) if (y.has(t)) inter++;
  return inter / (x.size + y.size - inter);
}

/** First balanced JSON object in a model reply (fenced or bare). */
export function extractJson(text: string): unknown {
  const fence = text.match(/```(?:json)?\s*\n([\s\S]*?)\n```/);
  const candidates = fence ? [fence[1], text] : [text];
  for (const c of candidates) {
    const start = c.indexOf('{');
    if (start < 0) continue;
    let depth = 0;
    let inStr = false;
    for (let i = start; i < c.length; i++) {
      const ch = c[i];
      if (inStr) {
        if (ch === '\\') i++;
        else if (ch === '"') inStr = false;
      } else if (ch === '"') inStr = true;
      else if (ch === '{') depth++;
      else if (ch === '}' && --depth === 0) {
        try {
          return JSON.parse(c.slice(start, i + 1));
        } catch {
          break;
        }
      }
    }
  }
  throw new Error('no JSON object found in model reply');
}
