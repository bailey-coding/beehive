// bwrap sandbox for the Bash tool of candidate agents (opt-in `--allow-bash`). The claude CLI itself must reach the API,
// so the network cannot be cut around it; instead EVERY Bash command is run through CLAUDE_CODE_SHELL_PREFIX, a script
// that execs `bwrap` around the shell invocation. The exact bwrap invocation is built here and proven by a model-independent
// probe before any real call. Inside: write access only to the agent's private root (worktree, scratch repo) and a
// private /tmp; read access only to that root, minimal system dirs and the node toolchain; no HOME, no ~/.claude, no .env,
// no harness dirs, no main checkout; all namespaces unshared (no network).
import fs from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import { exec, findOnPath } from './exec.ts';

export interface BashBox {
  /** Agent's private root: bound read-write at the same path (worktree, scratch repo and origin live here). */
  agentRoot: string;
  /** Working directory inside (the worktree). */
  cwd: string;
  /** Private tmp: bound read-write at the same path AND as /tmp, so the CLI (outside) and the shell (inside) share it. */
  tmpDir: string;
  /** Read-only extra paths (the CLI's shell-snapshot dir). */
  extraRo?: string[];
}

export const INNER_HOME = '/tmp/home';

const SYSTEM_LINKS: [string, string][] = [['usr/bin', '/bin'], ['usr/sbin', '/sbin'], ['usr/lib', '/lib'], ['usr/lib64', '/lib64']];
const ETC_FILES = ['/etc/ld.so.cache', '/etc/ld.so.conf', '/etc/passwd', '/etc/group', '/etc/nsswitch.conf'];
const ETC_DIRS = ['/etc/alternatives', '/etc/ld.so.conf.d'];

/** Read-only binds needed to run node when it is not under /usr (for example an nvm install under HOME): the install dir only. */
export function nodeRoBinds(execPath = process.execPath): string[] {
  const real = fs.realpathSync(execPath);
  if (real.startsWith('/usr/')) return [];
  return [path.dirname(path.dirname(real))];
}

/** The bwrap argument list (everything before `--`). Pure: tests inspect it, the probe and the real wrapper both use it. */
export function bwrapArgs(box: BashBox, opts: { execPath?: string; exists?: (p: string) => boolean } = {}): string[] {
  const exists = opts.exists ?? ((p: string) => fs.existsSync(p));
  const a = ['--unshare-all', '--die-with-parent', '--new-session', '--ro-bind', '/usr', '/usr'];
  for (const [target, link] of SYSTEM_LINKS) if (exists(link)) a.push('--symlink', target, link);
  for (const f of ETC_FILES) if (exists(f)) a.push('--ro-bind', f, f);
  for (const d of ETC_DIRS) if (exists(d)) a.push('--ro-bind', d, d);
  for (const p of nodeRoBinds(opts.execPath)) a.push('--ro-bind', p, p);
  a.push('--proc', '/proc', '--dev', '/dev');
  a.push('--bind', box.tmpDir, '/tmp'); // private tmp as /tmp
  a.push('--bind', box.tmpDir, box.tmpDir); // and at its real path, so paths the CLI hands out resolve
  a.push('--bind', box.agentRoot, box.agentRoot);
  for (const p of box.extraRo ?? []) a.push('--ro-bind', p, p);
  a.push('--chdir', box.cwd, '--clearenv');
  for (const [k, v] of Object.entries({ PATH: '/usr/local/bin:/usr/bin:/bin', HOME: INNER_HOME, TMPDIR: '/tmp', LANG: 'C.UTF-8', TERM: 'dumb', NO_COLOR: '1', CI: '1' })) a.push('--setenv', k, v);
  return a;
}

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/**
 * The prefix script Claude Code runs as `$CLAUDE_CODE_SHELL_PREFIX <shell> -c <command>` (it also copes with one
 * string argument). Lives outside every agent root; only the host executes it.
 */
export function prefixScript(bwrap: string, box: BashBox, opts: { execPath?: string } = {}): string {
  const args = bwrapArgs(box, opts).map(sq).join(' ');
  return `#!/bin/sh
# generated by the backtest harness: runs the Bash tool's shell inside bwrap
mkdir -p ${sq(box.tmpDir)}/home 2>/dev/null
if [ "$#" -eq 1 ]; then
  exec ${sq(bwrap)} ${args} -- /bin/sh -c "$1"
fi
exec ${sq(bwrap)} ${args} -- "$@"
`;
}

export function writePrefixScript(dir: string, bwrap: string, box: BashBox): string {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const p = path.join(dir, `bash-prefix-${path.basename(box.agentRoot)}.sh`);
  fs.writeFileSync(p, prefixScript(bwrap, box), { mode: 0o700 });
  return p;
}

export interface BashSandboxProof {
  ok: boolean;
  bwrap: string | null;
  /** Human-readable: which sandbox is active, or why it is not usable. */
  detail: string;
}

/**
 * Prove the exact invocation on this host, with no model: inside it a shell must not read a canary outside the root,
 * must not see HOME or /home, must not write outside (a host-side check), must not reach a host loopback listener or the
 * internet, must see its own loopback, and must be able to write in the root and in /tmp.
 */
export async function proveBashSandbox(opts: { which?: (n: string) => string | null } = {}): Promise<BashSandboxProof> {
  const bwrap = (opts.which ?? ((n: string) => findOnPath(n)))('bwrap');
  if (!bwrap) return { ok: false, bwrap: null, detail: 'bwrap (bubblewrap) not found on PATH' };
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'bt-bashprobe-'));
  const agentRoot = path.join(base, 'agent');
  const cwd = path.join(agentRoot, 'wt');
  const tmpDir = path.join(base, 'agent-tmp');
  const outside = path.join(base, 'outside');
  for (const d of [cwd, tmpDir, outside]) fs.mkdirSync(d, { recursive: true });
  fs.writeFileSync(path.join(outside, 'canary.txt'), 'SECRET');
  fs.writeFileSync(path.join(outside, '.env'), 'TOKEN=SECRET');
  const home = os.homedir();
  const homeCanary = path.join(home, `.bt-probe-canary-${process.pid}`);
  let homeCanaryWritten = false;
  try {
    fs.writeFileSync(homeCanary, 'SECRET');
    homeCanaryWritten = true;
  } catch {
    /* read-only HOME: the HOME check below still lists it */
  }
  const server = net.createServer((s) => s.destroy());
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
  const port = (server.address() as net.AddressInfo).port;
  try {
    const js = `
const fs=require('fs'),net=require('net');
const r={};
const rd=(p)=>{try{fs.readFileSync(p);return true}catch{return false}};
r.canary=rd(process.argv[1]); r.dotenv=rd(process.argv[1].replace('canary.txt','.env'));
r.homeCanary=rd(process.argv[5]);
try{r.homeListing=fs.readdirSync(process.argv[6]).length}catch{r.homeListing='absent'}
try{fs.writeFileSync(process.argv[2]+'/x.txt','x');r.writeOutside='wrote'}catch{r.writeOutside='refused'}
try{fs.writeFileSync(process.argv[3]+'/ok.txt','x');r.writeRoot=true}catch{r.writeRoot=false}
try{fs.writeFileSync('/tmp/ok.txt','x');r.writeTmp=true}catch{r.writeTmp=false}
r.homeEnv=process.env.HOME;
const tryConnect=(host,port)=>new Promise(res=>{const s=net.connect({host,port,timeout:2500});s.on('connect',()=>{s.destroy();res(true)});s.on('error',()=>res(false));s.on('timeout',()=>{s.destroy();res(false)})});
(async()=>{
  const own=net.createServer(c=>c.destroy()); await new Promise(ok=>own.listen(0,'127.0.0.1',ok));
  r.ownLoopback=await tryConnect('127.0.0.1',own.address().port); own.close();
  r.hostListener=await tryConnect('127.0.0.1',+process.argv[4]);
  r.internet=await tryConnect('1.1.1.1',443);
  console.log(JSON.stringify(r));process.exit(0);
})();`;
    const args = [...bwrapArgs({ agentRoot, cwd, tmpDir }), '--', 'node', '-e', js, path.join(outside, 'canary.txt'), outside, cwd, String(port), homeCanary, home];
    const r = await exec(bwrap, args, { cwd: os.tmpdir(), timeoutMs: 60_000, env: { PATH: process.env.PATH ?? '/usr/bin:/bin' } });
    let res: Record<string, unknown>;
    try {
      res = JSON.parse(r.stdout.trim().split('\n').pop() ?? '');
    } catch {
      return { ok: false, bwrap, detail: `bwrap could not run the probe (exit ${r.code}): ${r.stderr.trim().slice(-200)}` };
    }
    const hostWrote = fs.existsSync(path.join(outside, 'x.txt'));
    const problems: string[] = [];
    if (res.canary) problems.push('canary file outside the root is readable');
    if (res.dotenv) problems.push('.env outside the root is readable');
    if (res.homeCanary) problems.push('HOME canary is readable');
    if (res.homeListing !== 'absent') problems.push('HOME directory is visible');
    if (hostWrote) problems.push('a write outside the root reached the host');
    if (!res.writeRoot) problems.push('the root is not writable');
    if (!res.writeTmp) problems.push('/tmp is not writable');
    if (res.homeEnv !== INNER_HOME) problems.push(`HOME is ${String(res.homeEnv)}, expected ${INNER_HOME}`);
    if (!res.ownLoopback) problems.push('own loopback does not work inside');
    if (res.hostListener) problems.push('a host loopback listener is reachable');
    if (res.internet) problems.push('the internet is reachable');
    if (problems.length) return { ok: false, bwrap, detail: `isolation probe failed: ${problems.join('; ')}` };
    return { ok: true, bwrap, detail: `bubblewrap ${bwrap}: all namespaces unshared, read-only /usr and node toolchain, private root and /tmp, no HOME, no network` };
  } finally {
    server.close();
    if (homeCanaryWritten) fs.rmSync(homeCanary, { force: true });
    fs.rmSync(base, { recursive: true, force: true });
  }
}

/** Plain copy (never a symlink) of the harness's installed dependencies into an agent's worktree. */
export function copyDepsInto(depsRepo: string, wt: string): void {
  for (const rel of ['node_modules', 'cli/node_modules']) {
    const link = path.join(depsRepo, rel);
    if (!fs.existsSync(link)) continue;
    const src = fs.realpathSync(link); // even if the provider itself is a symlink, the agent gets a plain copy
    const dest = path.join(wt, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.cpSync(src, dest, { recursive: true, dereference: false, verbatimSymlinks: true }); // keep relative symlinks relative
  }
}
